// The machines this page can boot.
//
// v86 emulates a 32-bit x86 PC with a legacy BIOS: no 64-bit mode, no UEFI, no PAE. That one fact decides
// this list. A distro only belongs here if it still publishes an i386/i686 image that boots on a plain BIOS,
// and "modern Windows" ends at the NT 5.x line: Windows 7 and later need PAE and SSE2, and 10/11 are 64-bit
// only, so they cannot start however the image is served.
//
// Sizes are exact byte counts as the mirrors report them; v86 needs the length up front to place the disk.
// Every URL below was fetched with a byte-range request when it was added.

